#!/usr/bin/env python3
"""Builds CodecVectors.cs: small LZMA1 (raw) and FLAC streams of generated data, for the decoder unit tests.

Needs Python's lzma module and the flac encoder (1.4). The inputs come from the same generators as CodecInputs in
the tests, so only the compressed bytes are embedded.

    python3 -I make_codec_vectors.py > ../CodecVectors.cs
"""
import base64
import lzma
import os
import subprocess
import sys
import tempfile


class Lcg:
    def __init__(self, seed):
        self.x = seed

    def next(self):
        self.x = (self.x * 1103515245 + 12345) & 0x7FFFFFFF
        return self.x >> 8


def lzma_input():
    pattern = b"GameVault reads CHD discs. "
    rng = Lcg(1)
    out = bytearray()
    for i in range(6000):
        r = rng.next()
        out.append(pattern[i % len(pattern)] if r & 7 else r & 0xFF)
    return bytes(out)


def s16(v):
    return v & 0xFFFF


def flac_input(kind, samples=3000):
    rng = Lcg(7)
    out = bytearray()
    for t in range(samples):
        if kind == "smooth":
            left = (t * 37) % 2000 - 1000 + (rng.next() & 15)
            right = 700 - (t * 23) % 1400 + (rng.next() & 7)
        elif kind == "noise":
            left = (rng.next() & 0xFFFF) - 32768
            right = (rng.next() & 0xFFFF) - 32768
        else:  # "steps": constant runs, so constant subframes and wasted bits appear
            left = ((t // 700) * 4096) - 8192
            right = left
        out += s16(left).to_bytes(2, "little") + s16(right).to_bytes(2, "little")
    return bytes(out)


def flac_frames(raw, args, work):
    src = os.path.join(work, "in.raw")
    dst = os.path.join(work, "out.flac")
    with open(src, "wb") as f:
        f.write(raw)
    subprocess.run(["flac", "-s", "-f", "--force-raw-format", "--endian=little", "--sign=signed", "--channels=2",
                    "--bps=16", "--sample-rate=44100", *args, "-o", dst, src], check=True)
    data = open(dst, "rb").read()
    assert data[:4] == b"fLaC"
    pos = 4
    while True:  # skip the metadata blocks: CHD stores frames only
        last = data[pos] & 0x80
        length = int.from_bytes(data[pos + 1:pos + 4], "big")
        pos += 4 + length
        if last:
            break
    return data[pos:]


def emit(out, name, data, comment):
    encoded = base64.b64encode(data).decode()
    out.write("\n    /// <summary>" + comment + " (" + str(len(data)) + " bytes).</summary>\n")
    out.write("    public static readonly byte[] " + name + " = Convert.FromBase64String(\n")
    for i in range(0, len(encoded), 100):
        sep = " +" if i + 100 < len(encoded) else ");"
        out.write('        "' + encoded[i:i + 100] + '"' + sep + "\n")


def main():
    out = sys.stdout
    version = subprocess.run(["flac", "--version"], capture_output=True, text=True).stdout.strip()
    out.write("// Generated by Fixtures/make_codec_vectors.py (Python lzma, " + version + "). Do not edit.\n\n")
    out.write("namespace GameVault.Library.Tests.Discs;\n\ninternal static class CodecVectors\n{")
    filters = [{"id": lzma.FILTER_LZMA1, "lc": 3, "lp": 0, "pb": 2, "dict_size": 1 << 16}]
    emit(out, "Lzma", lzma.compress(lzma_input(), format=lzma.FORMAT_RAW, filters=filters),
         "LzmaInput as raw LZMA1, lc=3 lp=0 pb=2, with an end marker")
    with tempfile.TemporaryDirectory() as work:
        for name, kind, args, comment in [
            ("FlacSmoothBest", "smooth", ["-8"], "smooth input, flac -8 (LPC, adaptive stereo)"),
            ("FlacSmoothFast", "smooth", ["-0"], "smooth input, flac -0 (fixed predictors)"),
            ("FlacSmoothLong", "smooth", ["-8", "-l", "32", "-b", "2352", "--lax"], "smooth input, LPC order up to 32, block 2352"),
            ("FlacNoise", "noise", ["-5"], "noise, flac -5 (verbatim or escaped residuals)"),
            ("FlacSteps", "steps", ["-5", "-b", "576"], "constant runs, flac -5 -b 576"),
        ]:
            emit(out, name, flac_frames(flac_input(kind), args, work), comment)
    out.write("}\n")


if __name__ == "__main__":
    main()
